// ---------------------------------------------------------------------------
// The connector reference in docs/connectors.md.
//
// The docs have listed connectors the factory could not build, and missed
// ones it could, because the list was typed by hand. The reference table is
// therefore generated from the two switches that decide what a `type` value
// builds — createSourceBase and createSinkBase — and this test fails when the
// table and the switches disagree.
//
// The switches are read out of the source rather than probed by calling the
// constructors: building a connector needs its configuration, and an
// "unsupported type" error is the only answer that would tell the two cases
// apart. The source states the set plainly.

const connectorDoc = "../../docs/connectors.md"

const (
	referenceBegin = "<!-- BEGIN connector-types: generated by TestConnectorReferenceMatchesTheFactory, do not edit -->"
	referenceEnd   = "<!-- END connector-types -->"
)

// updateConnectorDoc rewrites the generated table instead of asserting against
// it. A flag rather than an env var, so regenerating is typed on purpose.
var updateConnectorDoc = flag.Bool("update-connector-doc", false,
	"rewrite the connector reference in "+connectorDoc+" from the factory")

// connectorTypes returns the string case labels of the switch on cfg.Type at
// the top level of the named function in factory.go.
func connectorTypes(t *testing.T, funcName string) []string {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "factory.go", nil, 0)
	if err != nil {
		t.Fatalf("parse factory.go: %v", err)
	}

	var fn *ast.FuncDecl
	for _, d := range file.Decls {
		if f, ok := d.(*ast.FuncDecl); ok && f.Name.Name == funcName {
			fn = f
		}
	}
	if fn == nil {
		t.Fatalf("factory.go has no function %s; the reference reads its switch", funcName)
	}

	var types []string
	for _, stmt := range fn.Body.List {
		sw, ok := stmt.(*ast.SwitchStmt)
		if !ok || !isCfgType(sw.Tag) {
			continue
		}
		for _, c := range sw.Body.List {
			for _, e := range c.(*ast.CaseClause).List {
				lit, ok := e.(*ast.BasicLit)
				if !ok || lit.Kind != token.STRING {
					t.Fatalf("%s: case label %s is not a string literal, so it cannot be listed",
						funcName, fset.Position(e.Pos()))
				}
				v, err := strconv.Unquote(lit.Value)
				if err != nil {
					t.Fatalf("unquote %s: %v", lit.Value, err)
				}
				types = append(types, v)
			}
		}
	}
	if len(types) == 0 {
		t.Fatalf("%s: no switch on cfg.Type found; the extraction broke, the factory did not empty", funcName)
	}
	slices.Sort(types)
	return slices.Compact(types)
}

func isCfgType(e ast.Expr) bool {
	sel, ok := e.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Type" {
		return false
	}
	id, ok := sel.X.(*ast.Ident)
	return ok && id.Name == "cfg"
}

// renderConnectorReference is the generated block, markers included.
func renderConnectorReference(sources, sinks []string) string {
	all := slices.Concat(sources, sinks)
	slices.Sort(all)
	all = slices.Compact(all)

	var b strings.Builder
	b.WriteString(referenceBegin + "\n\n")
	fmt.Fprintf(&b, "%d source types and %d sink types.\n\n", len(sources), len(sinks))
	b.WriteString("| `type` | Source | Sink |\n| :--- | :---: | :---: |\n")
	for _, typ := range all {
		src, snk := "", ""
		if slices.Contains(sources, typ) {
			src = "✓"
		}
		if slices.Contains(sinks, typ) {
			snk = "✓"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", typ, src, snk)
	}
	b.WriteString("\n" + referenceEnd)
	return b.String()
}

func TestConnectorReferenceMatchesTheFactory(t *testing.T) {
	want := renderConnectorReference(
		connectorTypes(t, "createSourceBase"),
		connectorTypes(t, "createSinkBase"),
	)

	path := filepath.FromSlash(connectorDoc)
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", connectorDoc, err)
	}
	doc := string(raw)

	begin := strings.Index(doc, referenceBegin)
	end := strings.Index(doc, referenceEnd)
	if begin < 0 || end < begin {
		t.Fatalf("%s has no generated connector reference between\n  %s\nand\n  %s",
			connectorDoc, referenceBegin, referenceEnd)
	}
	got := doc[begin : end+len(referenceEnd)]

	if got == want {
		return
	}
	if *updateConnectorDoc {
		updated := doc[:begin] + want + doc[end+len(referenceEnd):]
		if err := os.WriteFile(path, []byte(updated), 0o644); err != nil {
			t.Fatalf("write %s: %v", connectorDoc, err)
		}
		t.Logf("rewrote the connector reference in %s", connectorDoc)
		return
	}
	t.Fatalf("the connector reference in %s does not match the factory's switches.\n\n"+
		"want:\n%s\n\ngot:\n%s\n\n"+
		"If the factory change is intended, run:\n"+
		"  go test ./internal/factory/ -run TestConnectorReferenceMatchesTheFactory -update-connector-doc\n"+
		"and commit the result.", connectorDoc, want, got)
}
